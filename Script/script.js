let flashcardQuestionNumber = 0
let currentFlashcardList = ch6FlashcardList

const flashcardDisplay = document.getElementById("flashcardDisplay")
const answerButton = document.getElementById("answerButton")
const answerButtonText = document.getElementById("answerButtonText")
const chapterSelect = document.getElementById("chapterSelect")

chapterSelect.addEventListener("change", () => {
    if (chapterSelect.value == "chapter6") {
        currentFlashcardList = ch6FlashcardList
    } else if (chapterSelect.value == "chapter8") {
        currentFlashcardList = ch8FlashcardList
    } else if (chapterSelect.value == "chapter9") {
        currentFlashcardList = ch9FlashcardList
    }

    flashcardQuestionNumber = 0
    flashcardDisplay.textContent = currentFlashcardList[flashcardQuestionNumber].question
    answerButtonText.textContent = "Reveal Answer"
})

answerButton.addEventListener("click", () => {
    if (answerButtonText.textContent == "Reveal Answer") {
        flashcardDisplay.textContent = currentFlashcardList[flashcardQuestionNumber].answer
        answerButtonText.textContent = "Next =>"
    } else {
        flashcardQuestionNumber++

        if (flashcardQuestionNumber >= currentFlashcardList.length) {
            flashcardQuestionNumber = 0
        }

        flashcardDisplay.textContent = currentFlashcardList[flashcardQuestionNumber].question
        answerButtonText.textContent = "Reveal Answer"
    }
})

flashcardDisplay.textContent = currentFlashcardList[flashcardQuestionNumber].question

