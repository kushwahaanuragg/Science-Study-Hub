let currentQuestionList = ch6MCQList
let currentQuestion = 0

const chapterSelect = document.getElementById("chapterSelect")
const display = document.getElementById("MCQDisplay")
const options = document.querySelectorAll(".MCQOptions")

chapterSelect.addEventListener("change", () => {
    if (chapterSelect.value === "chapter6") {
        currentQuestionList = ch6MCQList
    } else if (chapterSelect.value === "chapter8") {
        currentQuestionList = ch8MCQList
    } else if (chapterSelect.value === "chapter9") {
        currentQuestionList = ch9MCQList
    }

    currentQuestion = 0
    showQuestion()
})

function showQuestion() {
    if (currentQuestion >= currentQuestionList.length) {
        display.textContent = "Quiz complete!"
        options.forEach((option) => {
            option.textContent = ""
            option.style.visibility = "hidden"
        })
        return
    }

    const question = currentQuestionList[currentQuestion]
    display.textContent = question.question

    options.forEach((option, index) => {
        option.textContent = question.options[index]
    })
}


options.forEach((option) => {
    option.addEventListener("click", () => {
        if (option.textContent === currentQuestionList[currentQuestion].correctAnswer) {
            currentQuestion++
            showQuestion()

            option.style.backgroundColor = "green"
            option.style.scale = "1.02"
        } else {
            option.style.backgroundColor = "red"
            option.style.scale = "0.98"
        }

        setTimeout(() => {
            option.style.backgroundColor = ""
            option.style.scale = "1"
        }, 1000)
    })
})

showQuestion()

