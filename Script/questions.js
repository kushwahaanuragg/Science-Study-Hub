// INITIAL VARIABLES
// ==========================================

let filteredList = [...questionList];

let activeFilters = {
    chapter: null,
    difficulty: null,
    length: null
};

let currentQuestion = 0;
let showingAnswer = false;

// ==========================================
// HTML ELEMENTS
// ==========================================

const display = document.getElementById("display");
const ansBtn = document.getElementById("ansBtn");
const applyFiltersBtn = document.getElementById("applyFiltersBtn");

// ==========================================
// FILTER SELECTION UI
// ==========================================

document.querySelectorAll("#filterSection p").forEach(btn => {


    btn.addEventListener("click", () => {

        btn.parentElement.querySelectorAll("p").forEach(option => {
            option.classList.toggle("active", option === btn);
        });

    });


});

// ==========================================
// FILTER FUNCTIONS
// ==========================================

function filterChapter(chapter) {
    activeFilters.chapter = chapter;
}

function filterDifficulty(difficulty) {
    activeFilters.difficulty = difficulty;
}

function filterLength(length) {
    activeFilters.length = length;
}

// ==========================================
// APPLY FILTERS
// ==========================================

function applyFilters() {


    filteredList = questionList.filter(question => {

        const chapterMatch =
            activeFilters.chapter === null ||
            question.chapter === activeFilters.chapter;

        const difficultyMatch =
            activeFilters.difficulty === null ||
            question.difficulty === activeFilters.difficulty;

        const lengthMatch =
            activeFilters.length === null ||
            question.length === activeFilters.length;

        return chapterMatch && difficultyMatch && lengthMatch;

    });

    currentQuestion = 0;
    showingAnswer = false;

    displayQuestion();


}

applyFiltersBtn.addEventListener("click", applyFilters);

// ==========================================
// DISPLAY QUESTIONS
// ==========================================

function displayQuestion() {
    if (filteredList.length === 0) {

        display.innerText = "No questions found!";
        ansBtn.style.display = "none";

        return;
    }

    ansBtn.style.display = "block";

    display.innerText = filteredList[currentQuestion].question;
    ansBtn.innerText = "Answer ->";


}

// ==========================================
// ANSWER & NEXT QUESTION
// ==========================================

ansBtn.addEventListener("click", () => {


    if (filteredList.length === 0) return;

    if (!showingAnswer) {

        display.innerText = filteredList[currentQuestion].answer;

        ansBtn.innerText = "Next Question ->";

        showingAnswer = true;

    }

    else {

        currentQuestion++;

        if (currentQuestion >= filteredList.length) {
            currentQuestion = 0;
        }

        showingAnswer = false;

        displayQuestion();

    }


});

// ==========================================
// CLEAR FILTERS
// ==========================================

function clearFilters() {
    activeFilters.chapter = null;
    activeFilters.difficulty = null;
    activeFilters.length = null;

    document.querySelectorAll("#filterSection p").forEach(btn => {
        btn.classList.remove("active");
    });

    applyFilters();

}

// ==========================================
// INITIAL DISPLAY
// ==========================================

displayQuestion();

